import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
import {pgcrypto} from '@electric-sql/pglite/contrib/pgcrypto';
import {hasGrant} from '../src/features/workspace/domain/types';
test('jefe crea proyectos; administradores editan permisos con aislamiento', {timeout:60000},async()=>{
 const db=new PGlite({extensions:{pgcrypto}});
 try {
    await db.exec(`create role anon; create role authenticated; create role service_role;
      create schema auth; create schema storage;
      create table auth.users(id uuid primary key, email text, raw_user_meta_data jsonb default '{}'::jsonb);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid default gen_random_uuid(),bucket_id text,name text,owner_id text,metadata jsonb);
      alter table storage.objects enable row level security;
      grant usage on schema storage to authenticated;grant select,insert on storage.objects to authenticated;
      create function storage.foldername(text) returns text[] language sql immutable as $$ select string_to_array($1,'/') $$;
    `);
    const sql=(path:string)=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
    await db.exec(sql('supabase/migrations/20260920000000_initial_schema.sql'));
    await db.exec(sql('supabase/migrations/20261010000000_interface_workflows.sql'));
    await db.exec(sql('supabase/migrations/20261010010000_team_assignments.sql'));
    await db.exec(sql('supabase/migrations/20261010020000_notifications_roles.sql'));
    await db.exec(sql('supabase/migrations/20261010030000_replace_roles.sql'));
    await db.exec(sql('supabase/migrations/20261010040000_personal_profile.sql'));
    await db.exec(sql('supabase/migrations/20261011000000_task_update_policy.sql'));
    await db.exec(sql('supabase/migrations/20261011010000_platform_organizations.sql'));
    await db.exec(sql('supabase/20_permisos_jefes_proyectos.sql'));
    await db.exec(sql('supabase/20_permisos_jefes_proyectos.sql'));

 const admin='11111111-1111-4111-8111-111111111111',lead='22222222-2222-4222-8222-222222222222';
 await db.query('insert into auth.users(id,email) values($1,$2),($3,$4)',[admin,'admin@example.test',lead,'lead@example.test']);
 await db.query("select private.bootstrap_organization('Uno','uno',$1)",[admin]);
 await db.query("select private.bootstrap_organization('Dos','dos',$1)",[admin]);
 const org=(await db.query<{id:string}>("select id from organizations where slug='uno'")).rows[0].id;
 const other=(await db.query<{id:string}>("select id from organizations where slug='dos'")).rows[0].id;
 await db.query("insert into organization_members(organization_id,user_id,status) values($1,$2,'active')",[org,lead]);
 const member=(await db.query<{id:string}>('select id from organization_members where user_id=$1',[lead])).rows[0].id;
 const role=(await db.query<{id:string}>("select id from roles where organization_id=$1 and code='project_manager'",[org])).rows[0].id;
 const project=(await db.query<{id:string}>("insert into projects(organization_id,code,name) values($1,'P1','Asignado') returning id",[org])).rows[0].id;
 await db.query("insert into member_role_assignments(organization_id,member_id,role_id,scope_type,project_id) values($1,$2,$3,'project',$4)",[org,member,role,project]);
 const actor=async(u:string)=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[u]);await db.exec('set role authenticated');};
 const save=async(o:string,r:string,ids:string[])=>db.query('select nexo_role_command($1,$2::jsonb)',['role.save',JSON.stringify({organization_id:o,id:r,name:'Jefe de proyecto',permission_ids:ids})]);
 await actor(lead);
 assert.equal((await db.query<{ok:boolean}>("select private.has_permission($1,'project.create') ok",[org])).rows[0].ok,true);
 await assert.rejects(db.query("insert into projects(organization_id,code,name,created_by) values($1,'FAIL','Ajeno',$2)",[other,lead]),/row-level security/);
 const created=(await db.query<{id:string}>("insert into projects(organization_id,code,name,created_by) values($1,'P2','Nuevo',$2) returning id",[org,lead])).rows[0].id;
 assert.equal((await db.query<{ok:boolean}>("select private.has_permission($1,'project.manage',$2) ok",[org,created])).rows[0].ok,true);
 assert.equal((await db.query<{n:number}>('select count(*)::int n from project_members where project_id=$1 and is_project_manager',[created])).rows[0].n,1);
 await assert.rejects(save(org,role,[]),/permiso/);
 await actor(admin);
 const ids=(await db.query<{permission_id:string}>('select permission_id from role_permissions where role_id=$1',[role])).rows.map(r=>r.permission_id);
 const createId=(await db.query<{id:string}>("select id from permissions where code='project.create'")).rows[0].id;
 await save(org,role,ids.filter(id=>id!==createId));
 await actor(lead);
 await assert.rejects(db.query("insert into projects(organization_id,code,name,created_by) values($1,'P3','Revocado',$2)",[org,lead]),/row-level security/);
 await actor(admin);await save(org,role,ids);
 const adminRole=(await db.query<{id:string}>("select id from roles where organization_id=$1 and code='admin'",[org])).rows[0].id;
 await save(org,adminRole,[]);
 assert.equal((await db.query<{ok:boolean}>("select private.has_permission($1,'access.manage') ok",[org])).rows[0].ok,true);
 await db.exec('reset role');
 await db.query('insert into platform_administrators(user_id) values($1)',[lead]);
 await actor(lead);await save(org,role,ids);
 assert.equal(hasGrant([{organizationId:org,scope:'project',projectId:project,areaId:null,codes:['project.create']}],'project.create',org),true);
 assert.equal(hasGrant([{organizationId:org,scope:'project',projectId:project,areaId:null,codes:['project.create']}],'project.create',other),false);
 } finally {await db.close();}
});
